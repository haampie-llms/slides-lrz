. "$(dirname "$0")/lib.sh"
work=$HOME/lrz-demo/work/anatomy; rm -rf "$work"; mkdir -p "$work"; cd "$work"
PROMPT_DIR="~/anatomy"
say "copy an image from Docker Hub into a plain directory (OCI layout)"
run "skopeo copy -q docker://ubuntu:26.04 oci:ubuntu:26.04"
run "find ubuntu -type f"
say "index.json -> manifest"
run "manifest=ubuntu/blobs/sha256/\$(jq -r '.manifests[0].digest[7:]' ubuntu/index.json)"
run "jq . \$manifest"
say "manifest -> config: just JSON"
run "jq '.config | {Env, Cmd}' ubuntu/blobs/sha256/\$(jq -r '.config.digest[7:]' \$manifest)"
say "manifest -> layer: just a tarball"
run "tar -tzf ubuntu/blobs/sha256/\$(jq -r '.layers[0].digest[7:]' \$manifest) | grep -E '^(usr/bin/bash|etc/os-release|usr/lib/x86_64-linux-gnu/libc.so.6)\$'"
end
