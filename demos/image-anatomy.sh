. "$(dirname "$0")/lib.sh"
work=$HOME/lrz-demo/work/anatomy; rm -rf "$work"; mkdir -p "$work"; cd "$work"
say "copy an image from Docker Hub into a plain directory (OCI layout)"
run "skopeo copy -q docker://ubuntu:26.04 oci:ubuntu:26.04"
run "find ubuntu -type f"
say "index.json points to the manifest, which points to config + layers"
run "cd ubuntu/blobs/sha256"
run "manifest=\$(jq -r '.manifests[0].digest[7:]' ../../index.json)"
run "jq 'del(.annotations, .layers[].annotations)' \$manifest"
say "the config is just JSON"
run "jq '.config | {Env, Cmd}' \$(jq -r '.config.digest[7:]' \$manifest)"
say "a layer is just a tarball"
run "tar -tzf \$(jq -r '.layers[0].digest[7:]' \$manifest) | grep -E '^(usr/bin/bash|usr/lib/x86_64-linux-gnu/libc.so.6)\$'"
end
